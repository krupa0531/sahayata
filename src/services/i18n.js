/**
 * Lookup a translation key with fallback
 */
export function t(key, lang = "en", fallback = "") {
  const selected = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return selected[key] || TRANSLATIONS.en[key] || fallback || key;
}

/**
 * Get current saved language
 */
export function getSavedLanguage() {
  try {
    return localStorage.getItem("sahayata_lang") || "en";
  } catch (_) {
    return "en";
  }
}

/**
 * Save language and broadcast to all windows/components
 */
export function saveLanguage(lang) {
  try {
    localStorage.setItem("sahayata_lang", lang);
    localStorage.setItem("sai_language", lang);
    window.dispatchEvent(new CustomEvent("sahayata_lang_change", { detail: lang }));
    window.dispatchEvent(new CustomEvent("sai_language_switch", { detail: { lang } }));
  } catch (_) {}
}
